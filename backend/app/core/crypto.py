"""Cryptographic and PII protection helpers.

Provides field-level AES-256-GCM envelope encryption (SEC-02) and data masking
for sensitive employee fields (PAN, Aadhaar, Bank account, IFSC).
"""

from __future__ import annotations

import base64
import hashlib
import os

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from app.core.config import settings

_PREFIX = "v1:"


def _get_encryption_key() -> bytes:
    """Derive a deterministic 256-bit key from settings."""
    raw_key = settings.pii_encryption_key.encode("utf-8")
    return hashlib.sha256(raw_key).digest()


def encrypt_pii(plaintext: str | None, context: str | None = None) -> str | None:
    """Encrypt a PII string using AES-256-GCM.

    Returns a version-prefixed, base64-encoded string: 'v1:<nonce+ciphertext+tag>'.
    """
    if plaintext is None:
        return None
    val = plaintext.strip()
    if not val:
        return None

    key = _get_encryption_key()
    aesgcm = AESGCM(key)
    nonce = os.urandom(12)  # Standard 96-bit nonce for GCM
    aad = context.encode("utf-8") if context else None

    ciphertext = aesgcm.encrypt(nonce, val.encode("utf-8"), aad)
    packed = nonce + ciphertext
    b64 = base64.urlsafe_b64encode(packed).decode("ascii")
    return f"{_PREFIX}{b64}"


def decrypt_pii(encrypted_payload: str | None, context: str | None = None) -> str | None:
    """Decrypt a PII ciphertext string generated by `encrypt_pii`."""
    if encrypted_payload is None:
        return None
    val = encrypted_payload.strip()
    if not val:
        return None

    if val.startswith(_PREFIX):
        val = val[len(_PREFIX) :]

    try:
        raw = base64.urlsafe_b64decode(val.encode("ascii"))
        if len(raw) < 28:  # 12 bytes nonce + 16 bytes tag minimum
            return None
        nonce = raw[:12]
        ciphertext = raw[12:]
        key = _get_encryption_key()
        aesgcm = AESGCM(key)
        aad = context.encode("utf-8") if context else None
        plaintext_bytes = aesgcm.decrypt(nonce, ciphertext, aad)
        return plaintext_bytes.decode("utf-8")
    except Exception:
        return None


def mask_pan(pan: str | None) -> str | None:
    """Mask PAN number according to SEC-02 (e.g. XXXXX1234)."""
    if not pan:
        return None
    clean = pan.strip().upper()
    if len(clean) == 10 and clean[5:9].isdigit():
        return f"XXXXX{clean[5:9]}"
    if len(clean) >= 4:
        return f"{'X' * (len(clean) - 4)}{clean[-4:]}"
    return "XXXX"


def mask_aadhaar(aadhaar: str | None) -> str | None:
    """Mask 12-digit Aadhaar number according to SEC-02 (e.g. XXXXXXXX1234)."""
    if not aadhaar:
        return None
    clean = "".join(aadhaar.strip().split())
    if len(clean) >= 4:
        return f"XXXXXXXX{clean[-4:]}" if len(clean) == 12 else f"{'X' * (len(clean) - 4)}{clean[-4:]}"
    return "XXXXXXXX"


def mask_bank_account(account: str | None) -> str | None:
    """Mask Bank Account number showing only the last 4 digits."""
    if not account:
        return None
    clean = account.strip()
    if len(clean) >= 4:
        mask_len = max(len(clean) - 4, 4)
        return f"{'X' * mask_len}{clean[-4:]}"
    return "XXXX"


def mask_bank_ifsc(ifsc: str | None) -> str | None:
    """Mask Bank IFSC code."""
    if not ifsc:
        return None
    clean = ifsc.strip().upper()
    if len(clean) >= 4:
        return f"{'X' * (len(clean) - 4)}{clean[-4:]}"
    return "XXXX"
